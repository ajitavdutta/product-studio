from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect

BACKEND_DIR = Path(__file__).resolve().parents[2]

DOCUMENT_COLUMNS = {
    "id",
    "kind",
    "name",
    "schema_version",
    "revision",
    "body",
    "created_at",
    "updated_at",
}


@pytest.fixture
def alembic_config(tmp_database_url: str) -> Config:
    config = Config(str(BACKEND_DIR / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    config.set_main_option("sqlalchemy.url", tmp_database_url)
    return config


def table_names(database_url: str) -> set[str]:
    engine = create_engine(database_url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def column_names(database_url: str, table: str) -> set[str]:
    engine = create_engine(database_url)
    try:
        return {column["name"] for column in inspect(engine).get_columns(table)}
    finally:
        engine.dispose()


def test_upgrade_head_creates_documents_table(
    alembic_config: Config, tmp_database_url: str
) -> None:
    command.upgrade(alembic_config, "head")

    assert column_names(tmp_database_url, "documents") == DOCUMENT_COLUMNS


def test_models_match_migrations(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")

    # Raises AutogenerateDiffsDetected if a model changed without a migration.
    command.check(alembic_config)


def test_downgrade_base_drops_documents(alembic_config: Config, tmp_database_url: str) -> None:
    command.upgrade(alembic_config, "head")

    command.downgrade(alembic_config, "base")

    assert "documents" not in table_names(tmp_database_url)
